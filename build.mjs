// Build: bundles src/app.js (+ Three.js r160, OrbitControls, RoomEnvironment) with esbuild into ONE
// classic (non-module) IIFE script and inlines it into src/template.html → ./index.html.
// The result has no imports and no network access, so it runs from file:// by double-click.
//
//   npm install      (once; needs network only at build time)
//   npm run build    (or: node build.mjs)
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/app.js'],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2020', 'safari15'],
  legalComments: 'none',
  write: false,
});
let js = result.outputFiles[0].text;
// Guard: a literal "</script" inside the bundle would end the inline <script> early.
js = js.replace(/<\/script/gi, '<\\/script');

const tpl = readFileSync('src/template.html', 'utf8');
if (!tpl.includes('/*__APP_BUNDLE__*/')) throw new Error('placeholder missing in template');
const banner = `/* Auscultation Simulator — generated by build.mjs from src/. Do not edit; edit src/ and rebuild.\n   Includes Three.js r160 (MIT, © 2010-2023 three.js authors). */\n`;
const html = tpl.replace('/*__APP_BUNDLE__*/', () => banner + js);
writeFileSync('index.html', html);
console.log(`index.html written: ${(html.length / 1024).toFixed(0)} KB`);
